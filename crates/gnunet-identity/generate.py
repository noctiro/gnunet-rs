#!/usr/bin/env python3
"""Generate locale-neutral lowercase/Final_Sigma tables from pinned public UCD18."""
from pathlib import Path
import argparse, hashlib, json, zipfile
parser=argparse.ArgumentParser();parser.add_argument('--ucd18',required=True);parser.add_argument('--output',required=True)
a=parser.parse_args();raw=Path(a.ucd18).read_bytes();digest=hashlib.sha256(raw).hexdigest()
assert digest=='7b3e555514060b92290d154f53655c5eb0fa62b16eb04c03434ff72d1a66a0d8'
with zipfile.ZipFile(Path(a.ucd18)) as z:
    sources={n:z.read(n) for n in ('UnicodeData.txt','SpecialCasing.txt','DerivedCoreProperties.txt')}
lower={}
for line in sources['UnicodeData.txt'].decode().splitlines():
    f=line.split(';');cp=int(f[0],16)
    if f[13]:lower[cp]=[int(f[13],16)]
conditions=[]
for line in sources['SpecialCasing.txt'].decode().splitlines():
    body=line.split('#')[0].strip()
    if not body:continue
    f=[s.strip() for s in body.split(';')]
    if not f[4]:lower[int(f[0],16)]=[int(c,16) for c in f[1].split()]
    elif not any(c in ('tr','az','lt') for c in f[4].split()):conditions.append((f[0],f[4]))
assert conditions==[('03A3','Final_Sigma')]
props={'Cased':[],'Case_Ignorable':[]}
for line in sources['DerivedCoreProperties.txt'].decode().splitlines():
    body=line.split('#')[0].strip()
    if not body:continue
    f=[s.strip() for s in body.split(';')]
    if f[1] not in props:continue
    r=f[0].split('..');lo=int(r[0],16);hi=int(r[-1],16);v=props[f[1]]
    if v and v[-1][1]+1==lo:v[-1]=(v[-1][0],hi)
    else:v.append((lo,hi))
rows=[];values=[]
for cp,seq in sorted(lower.items()):
    if seq==[cp]:continue
    rows.append((cp,len(values),len(seq)));values+=seq
text='//! Generated by generate.py from public Unicode18; see data/provenance.json.\n'
text+='pub(crate) const LOWER: &[(u32,u16,u8)] = &[\n'+''.join(f'    (0x{cp:X},{offset},{n}),\n' for cp,offset,n in rows)+'];\n'
text+='pub(crate) const LOWERED: &[u32] = &[\n'+''.join('    '+','.join(f'0x{cp:X}' for cp in values[i:i+16])+',\n' for i in range(0,len(values),16))+'];\n'
for name,rs in props.items():
    key={'Cased':'CASED','Case_Ignorable':'IGNORABLE'}[name]
    text+=f'pub(crate) const {key}: &[(u32,u32)] = &[\n'+''.join(f'    (0x{lo:X},0x{hi:X}),\n' for lo,hi in rs)+'];\n'
p=Path(a.output);p.mkdir(parents=True,exist_ok=True);(p/'src/tables.rs').write_text(text)
(p/'data/provenance.json').write_text(json.dumps({'unicode':'18.0.0','profile':'libunistring1.5 locale NULL lowercase, NFD','ucd18_zip_sha256':digest,'sources':{n:hashlib.sha256(v).hexdigest() for n,v in sources.items()},'lowercase_rows':len(rows),'lowercase_scalars':len(values),'locale_neutral_contexts':conditions,'license':'COPYING.unicode'},indent=2)+'\n')
