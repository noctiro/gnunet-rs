//! Active v0.29.1 generic SET IPC and CADET peer frames.
//!
//! This is the installed contrib `set` protocol, distinct from SETI/SETU even
//! where registered message numbers alias. The actual endpoint/channel selects
//! the protocol. Parsing does not create sets, authenticate peers, reconcile
//! elements, decompress strata or grant operation/iteration completion.
//!
//! Unpacked reference uint64 fields require an explicit C alignment profile.
//! IBF payloads contain native-word columns, not interleaved network-order
//! buckets. Cookies are opaque four-byte echoes. No ABI guessing or negotiation
//! is added. Element-message alignment padding is ignored on input, as in C,
//! and emitted canonically as zero.
use super::{Frame, MessageHeader, MessageType, message_type as mt};
use gnunet_types::Error;

/// Maximum single nested application context, including its own message header.
pub const CONTEXT_MAX: usize = (1 << 16) - 1024;
/// Whole old SET union element prefix, including its header, type and padding.
/// Both ordinary and full-transfer element messages use this exact extent.
pub const UNION_ELEMENT_PREFIX: usize = 8;
/// Actual serialized old SET IBF bucket contribution: key8 + hash4 + count1.
pub const IBF_BUCKET_BYTES: usize = 13;
/// Actual uncompressed old SET strata count.
pub const STRATA_COUNT: usize = 32;
/// Actual bucket count per old SET stratum.
pub const STRATA_BUCKETS: usize = 80;
/// Exact uncompressed strata data extent, without its enclosing frame header.
pub const STRATA_BYTES: usize = STRATA_COUNT * STRATA_BUCKETS * IBF_BUCKET_BYTES;
/// Largest IBF order generated by the ordinary reference union sender.
pub const MAX_IBF_ORDER: u8 = 20;

/// Actual target's native-word order for IBF data and element fingerprints.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Order {
    /// Reference C little-endian host.
    Little,
    /// Reference C big-endian host.
    Big,
}
impl Order {
    /// Encode the actual native16 scalar (including size/type fingerprint input).
    #[must_use]
    pub const fn u16(self, value: u16) -> [u8; 2] {
        match self {
            Self::Little => value.to_le_bytes(),
            Self::Big => value.to_be_bytes(),
        }
    }
    /// Encode an actual native32 IBF hash word.
    #[must_use]
    pub const fn u32(self, value: u32) -> [u8; 4] {
        match self {
            Self::Little => value.to_le_bytes(),
            Self::Big => value.to_be_bytes(),
        }
    }
    /// Encode an actual native64 IBF/inquiry key word.
    #[must_use]
    pub const fn u64(self, value: u64) -> [u8; 8] {
        match self {
            Self::Little => value.to_le_bytes(),
            Self::Big => value.to_be_bytes(),
        }
    }
    /// Decode a target-native16 scalar.
    #[must_use]
    pub const fn read16(self, value: [u8; 2]) -> u16 {
        match self {
            Self::Little => u16::from_le_bytes(value),
            Self::Big => u16::from_be_bytes(value),
        }
    }
    /// Decode a target-native32 scalar.
    #[must_use]
    pub const fn read32(self, value: [u8; 4]) -> u32 {
        match self {
            Self::Little => u32::from_le_bytes(value),
            Self::Big => u32::from_be_bytes(value),
        }
    }
    /// Decode a target-native64 scalar.
    #[must_use]
    pub const fn read64(self, value: [u8; 8]) -> u64 {
        match self {
            Self::Little => u64::from_le_bytes(value),
            Self::Big => u64::from_be_bytes(value),
        }
    }
}
/// Explicit C source ABI; never inferred from incoming frames.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Abi {
    /// Native-word order for actual IBF/fingerprint algorithms.
    pub order: Order,
    /// Reference uint64 alignment, exactly4 or8.
    pub align64: u8,
}
impl Abi {
    /// Local Rust target ABI selection; use an explicit known C profile remotely.
    #[must_use]
    pub const fn native() -> Self {
        Self {
            order: if cfg!(target_endian = "little") {
                Order::Little
            } else {
                Order::Big
            },
            align64: core::mem::align_of::<u64>() as u8,
        }
    }
    /// Reject unknown alignment instead of guessing another layout.
    pub fn validate(self) -> Result<(), Error> {
        if matches!(self.align64, 4 | 8) {
            Ok(())
        } else {
            Err(Error::Unsupported)
        }
    }
    /// Exact generic SET_RESULT fixed prefix, including compiler padding.
    #[must_use]
    pub const fn result_len(self) -> usize {
        if self.align64 == 8 { 24 } else { 20 }
    }
    /// Exact SE/SEC prefix with its unpacked uint64 set size.
    #[must_use]
    pub const fn strata_len(self) -> usize {
        if self.align64 == 8 { 16 } else { 12 }
    }
    const fn wide(self) -> usize {
        if self.align64 == 8 { 8 } else { 4 }
    }
}
