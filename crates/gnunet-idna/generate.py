#!/usr/bin/env python3
"""Reproduce Unicode 15.1 Rust tables from fixed official source bytes."""
import hashlib,json,pathlib,zipfile,argparse,subprocess
ROOT=pathlib.Path(__file__).resolve().parent
parser=argparse.ArgumentParser(description=__doc__)
action=parser.add_mutually_exclusive_group(required=True)
action.add_argument('--check',action='store_true')
action.add_argument('--output',type=pathlib.Path)
parser.add_argument('--libidn2-source',type=pathlib.Path,required=True)
parser.add_argument('--ucd15',type=pathlib.Path,required=True)
parser.add_argument('--ucd18',type=pathlib.Path,required=True)
args=parser.parse_args()
DEST=ROOT if args.check else args.output.resolve()
if not args.check:
 assert not DEST.is_relative_to(ROOT) and not ROOT.is_relative_to(DEST),'Generated output and source must be disjoint'
 DEST.mkdir(parents=True,exist_ok=False)
 (DEST/'src').mkdir();(DEST/'data').mkdir()
UCD=args.ucd15; LIB=args.libidn2_source/'lib'
assert hashlib.sha256(UCD.read_bytes()).hexdigest()=='cb1c663d053926500cd501229736045752713a066bd75802098598b7a7056177'
z=zipfile.ZipFile(UCD)
inputs={}
def source(name,archive=False):
 b=z.read(name) if archive else (LIB/name).read_bytes()
 digest=hashlib.sha256(b).hexdigest()
 if not archive:
  expected={'IdnaMappingTable.txt':'402cbd285f1f952fcd0834b63541d54f69d3d8f1b8f8599bf71a1a14935f82c4','Idna2008.txt':'0729ec8d63ede7fe9f90b14e069cee550050bbdecc0356162a975d3aa9cb6322','DerivedNormalizationProps.txt':'8875dccee2bc1a7c1fe568a3b502a9e78c9e0495afd96b6568b4294d0ed1f7e1'}
  assert digest==expected[name],name+' source hash mismatch'
 inputs[('UCD-15.1.0.zip:' if archive else 'libidn2-2.3.8/lib/')+name]=digest
 return b.decode('utf8')
def rows(text):
 for line in text.splitlines():
  line=line.split('#',1)[0].strip()
  if line: yield [x.strip() for x in line.split(';')]
def bounds(s):
 a,*b=s.split('..');return int(a,16),int(b[0],16) if b else int(a,16)
def compress(values):
 r=[]
 for cp,v in sorted(values.items()):
  if r and r[-1][1]+1==cp and r[-1][2]==v: r[-1]=(r[-1][0],cp,v)
  else:r.append((cp,cp,v))
 return r
mapping=[];mapchars=[]
statuses={'valid':0,'ignored':1,'mapped':2,'deviation':3,'disallowed':4,'disallowed_STD3_valid':5,'disallowed_STD3_mapped':6}
for r in rows(source('IdnaMappingTable.txt')):
 a,b=bounds(r[0]);seq=[int(q,16) for q in r[2].split()] if len(r)>2 else []
 mapping.append((a,b,statuses[r[1]],len(mapchars),len(seq)));mapchars+=seq
valid=[]
for r in rows(source('Idna2008.txt')):
 a,b=bounds(r[0]);valid.append((a,b,{'PVALID':0,'CONTEXTJ':1,'CONTEXTO':2,'DISALLOWED':3,'UNASSIGNED':4}[r[1]]))
ccc={};marks={};bidi={};decomp={}
bidival={'L':0,'R':1,'AL':2,'EN':3,'AN':4,'NSM':5,'ES':6,'CS':7,'ET':8,'ON':9,'BN':10}
last=None
for r in rows(source('UnicodeData.txt',True)):
 cp=int(r[0],16)
 if r[1].endswith(', First>'): last=cp;continue
 ran=range(last,cp+1) if r[1].endswith(', Last>') else [cp];last=None
 for x in ran:
  if int(r[3]):ccc[x]=int(r[3])
  if r[2] in ('Mn','Mc','Me'):marks[x]=1
  if r[4] in bidival and bidival[r[4]]:bidi[x]=bidival[r[4]]
 if r[5] and not r[5].startswith('<'):decomp[cp]=[int(x,16) for x in r[5].split()]
# Full Composition Exclusion is the canonical pair restriction in UAX15.
excluded=set()
for r in rows(source('DerivedNormalizationProps.txt')):
 if r[1]=='Full_Composition_Exclusion':
  a,b=bounds(r[0]);excluded.update(range(a,b+1))
def flat(cp):
 if cp not in decomp:return [cp]
 return sum([flat(x) for x in decomp[cp]],[])
flatseq=[];dectable=[]
for cp in sorted(decomp):
 seq=flat(cp);dectable.append((cp,len(flatseq),len(seq)));flatseq+=seq
pairs=sorted((s[0],s[1],cp) for cp,s in decomp.items() if len(s)==2 and cp not in excluded)
jt={}
for r in rows(source('extracted/DerivedJoiningType.txt',True)):
 if r[1] not in ('L','R','D','T','C'):continue
 a,b=bounds(r[0]);jt.update((cp,{'L':1,'R':2,'D':3,'T':4,'C':5}[r[1]]) for cp in range(a,b+1))
scripts={}
for r in rows(source('Scripts.txt',True)):
 if r[1] not in ('Greek','Hebrew','Hiragana','Katakana','Han'):continue
 a,b=bounds(r[0]);scripts.update((cp,{'Greek':1,'Hebrew':2,'Hiragana':3,'Katakana':4,'Han':5}[r[1]]) for cp in range(a,b+1))
out=['// Generated by generate.py from the pinned official Unicode15.1 and18.0 inputs.\n// Unicode data license: see data/LICENSE-UNICODE.txt.\n']
def table(name,typ,rows):
 out.append('pub(super) static '+name+': &['+typ+'] = &[\n')
 for row in rows:
  out.append('('+','.join(hex(x) for x in row)+'),\n' if isinstance(row,tuple) else hex(row)+',\n')
 out.append('];\n')
table('MAPPING','(u32,u32,u8,u16,u8)',mapping)
table('MAPCHARS','u32',mapchars)
table('VALIDITY','(u32,u32,u8)',valid)
table('CCC','(u32,u32,u8)',compress(ccc))
table('MARK','(u32,u32,u8)',compress(marks))
table('BIDI','(u32,u32,u8)',compress(bidi))
table('JOIN','(u32,u32,u8)',compress(jt))
table('SCRIPT','(u32,u32,u8)',compress(scripts))
table('DECOMPOSITION','(u32,u16,u8)',dectable)
table('DECOMPOSED','u32',flatseq)
table('COMPOSITION','(u32,u32,u32)',pairs)
# Runtime profile for the actual independently built C dependency: libunistring1.5.
UCD18=args.ucd18
assert hashlib.sha256(UCD18.read_bytes()).hexdigest()=='7b3e555514060b92290d154f53655c5eb0fa62b16eb04c03434ff72d1a66a0d8'
z18=zipfile.ZipFile(UCD18)
def source18(name):
 b=z18.read(name);inputs['UCD-18.0.0.zip:'+name]=hashlib.sha256(b).hexdigest();return b.decode('utf8')
ccc18={};marks18={};bidi18={};decomp18={};last=None
for r in rows(source18('UnicodeData.txt')):
 cp=int(r[0],16)
 if r[1].endswith(', First>'):last=cp;continue
 ran=range(last,cp+1) if r[1].endswith(', Last>') else [cp];last=None
 for x in ran:
  if int(r[3]):ccc18[x]=int(r[3])
  if r[2] in ('Mn','Mc','Me'):marks18[x]=1
  if r[4] in bidival and bidival[r[4]]:bidi18[x]=bidival[r[4]]
 if r[5] and not r[5].startswith('<'):decomp18[cp]=[int(x,16) for x in r[5].split()]
excluded18=set()
for r in rows(source18('DerivedNormalizationProps.txt')):
 if r[1]=='Full_Composition_Exclusion':
  a,b=bounds(r[0]);excluded18.update(range(a,b+1))
def flat18(cp):
 if cp not in decomp18:return [cp]
 return sum([flat18(x) for x in decomp18[cp]],[])
flatseq18=[];dectable18=[]
for cp in sorted(decomp18):
 seq=flat18(cp);dectable18.append((cp,len(flatseq18),len(seq)));flatseq18+=seq
assert max(x[2] for x in dectable18)==4
pairs18=sorted((v[0],v[1],cp) for cp,v in decomp18.items() if len(v)==2 and cp not in excluded18)
jt18={}
for r in rows(source18('extracted/DerivedJoiningType.txt')):
 if r[1] not in ('L','R','D','T','C'):continue
 a,b=bounds(r[0]);jt18.update((cp,{'L':1,'R':2,'D':3,'T':4,'C':5}[r[1]]) for cp in range(a,b+1))
scripts18={}
for r in rows(source18('Scripts.txt')):
 if r[1] not in ('Greek','Hebrew','Hiragana','Katakana','Han'):continue
 a,b=bounds(r[0]);scripts18.update((cp,{'Greek':1,'Hebrew':2,'Hiragana':3,'Katakana':4,'Han':5}[r[1]]) for cp in range(a,b+1))
table('CCC18','(u32,u32,u8)',compress(ccc18))
table('MARK18','(u32,u32,u8)',compress(marks18))
table('BIDI18','(u32,u32,u8)',compress(bidi18))
table('JOIN18','(u32,u32,u8)',compress(jt18))
table('SCRIPT18','(u32,u32,u8)',compress(scripts18))
table('DECOMPOSITION18','(u32,u16,u8)',dectable18)
table('DECOMPOSED18','u32',flatseq18)
table('COMPOSITION18','(u32,u32,u32)',pairs18)
generated=subprocess.run(['rustfmt','+1.99.1','--edition','2024','--emit','stdout'],input=''.join(out),capture_output=True,text=True,check=True).stdout
if args.check:assert (ROOT/'src/tables.rs').read_text()==generated,'generated tables changed'
else:(DEST/'src/tables.rs').write_text(generated)
provenance=json.dumps({'unicode_version':'15.1.0','libidn2_version':'2.3.8','libidn2_tar_sha256':'f557911bf6171621e1f72ff35f5b1825bb35b52ed45325dcdee931e5d3c0787a','ucd_zip_sha256':hashlib.sha256(UCD.read_bytes()).hexdigest(),'runtime_unicode_version':'18.0.0','ucd18_zip_sha256':hashlib.sha256(UCD18.read_bytes()).hexdigest(),'source_inputs':inputs,'table_sha256':hashlib.sha256(generated.encode()).hexdigest(),'max_canonical_decomposition':max(x[2] for x in dectable),'counts':{'mapping':len(mapping),'mapped_codepoints':len(mapchars),'validity':len(valid),'decomposition':len(dectable),'composition':len(pairs),'ccc_ranges':len(compress(ccc)),'joining_ranges':len(compress(jt))}},indent=2)+'\n'
if args.check:
 assert (ROOT/'data/provenance.json').read_text()==provenance,'provenance changed'
 assert (ROOT/'data/COPYING.unicode-libidn2').read_bytes()==(LIB.parent/'COPYING.unicode').read_bytes()
 assert (ROOT/'data/UCD-ReadMe.txt').read_bytes()==z.read('ReadMe.txt')
else:
 (DEST/'data/provenance.json').write_text(provenance)
 (DEST/'data/COPYING.unicode-libidn2').write_bytes((LIB.parent/'COPYING.unicode').read_bytes())
 (DEST/'data/UCD-ReadMe.txt').write_bytes(z.read('ReadMe.txt'))
print(provenance)
